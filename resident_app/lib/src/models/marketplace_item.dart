class MarketplaceItem {
  final String id;
  final String name;
  final double price;
  final String category;
  final String condition;
  final String imagePath;

  MarketplaceItem({
    required this.id,
    required this.name,
    required this.price,
    required this.category,
    required this.condition,
    required this.imagePath,
  });
}
